-- Active Directory architecture laboratory.
-- Dialect: PostgreSQL 15 or later.
--
-- This relational model represents forests, trees, domains, trust
-- relationships, directory objects, LDAP search metadata, DNS records,
-- and operational dependencies. It is an educational model, not a schema
-- extracted from Microsoft's internal AD DS database.

BEGIN;

DROP VIEW IF EXISTS v_domain_controller_discovery CASCADE;
DROP VIEW IF EXISTS v_enabled_forest_trusts CASCADE;
DROP VIEW IF EXISTS v_directory_objects CASCADE;
DROP TABLE IF EXISTS service_observations CASCADE;
DROP TABLE IF EXISTS dns_records CASCADE;
DROP TABLE IF EXISTS ldap_search_audit CASCADE;
DROP TABLE IF EXISTS directory_objects CASCADE;
DROP TABLE IF EXISTS trusts CASCADE;
DROP TABLE IF EXISTS domains CASCADE;
DROP TABLE IF EXISTS forests CASCADE;

CREATE TABLE forests (
    forest_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    root_dns_name TEXT NOT NULL UNIQUE,
    forest_functional_level TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_forest_root_name CHECK (
        root_dns_name = lower(root_dns_name)
        AND root_dns_name !~ '\.\.'
        AND root_dns_name !~ '(^\.|\.$)'
        AND length(root_dns_name) <= 253
    ),
    CONSTRAINT ck_forest_functional_level CHECK (
        forest_functional_level IN (
            'Windows Server 2016',
            'Windows Server 2019',
            'Windows Server 2022',
            'Windows Server 2025',
            'Laboratory'
        )
    )
);

CREATE TABLE domains (
    domain_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    forest_id BIGINT NOT NULL REFERENCES forests(forest_id),
    dns_name TEXT NOT NULL UNIQUE,
    parent_domain_id BIGINT REFERENCES domains(domain_id),
    domain_sid TEXT UNIQUE,
    is_forest_root BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_domain_name CHECK (
        dns_name = lower(dns_name)
        AND dns_name !~ '\.\.'
        AND dns_name !~ '(^\.|\.$)'
        AND length(dns_name) <= 253
    ),
    CONSTRAINT ck_domain_parent CHECK (
        parent_domain_id IS NULL OR parent_domain_id <> domain_id
    ),
    CONSTRAINT ck_root_parent CHECK (
        NOT is_forest_root OR parent_domain_id IS NULL
    ),
    CONSTRAINT uq_domain_forest_name UNIQUE (forest_id, dns_name)
);

CREATE UNIQUE INDEX uq_one_root_domain_per_forest
    ON domains(forest_id)
    WHERE is_forest_root;

CREATE INDEX idx_domains_parent
    ON domains(parent_domain_id);

CREATE TABLE trusts (
    trust_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_forest_id BIGINT NOT NULL REFERENCES forests(forest_id),
    target_forest_id BIGINT NOT NULL REFERENCES forests(forest_id),
    trust_scope TEXT NOT NULL,
    direction TEXT NOT NULL,
    is_transitive BOOLEAN NOT NULL DEFAULT TRUE,
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_trust_scope CHECK (
        trust_scope IN ('DOMAIN', 'FOREST', 'EXTERNAL')
    ),
    CONSTRAINT ck_trust_direction CHECK (
        direction IN ('INBOUND', 'OUTBOUND', 'BIDIRECTIONAL')
    ),
    CONSTRAINT ck_trust_not_self CHECK (
        source_forest_id <> target_forest_id
    ),
    CONSTRAINT uq_trust_pair_scope UNIQUE (
        source_forest_id, target_forest_id, trust_scope
    )
);

CREATE INDEX idx_trusts_source_enabled
    ON trusts(source_forest_id, is_enabled);

CREATE INDEX idx_trusts_target_enabled
    ON trusts(target_forest_id, is_enabled);

CREATE TABLE directory_objects (
    object_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain_id BIGINT NOT NULL REFERENCES domains(domain_id),
    distinguished_name TEXT NOT NULL,
    object_class TEXT NOT NULL,
    sam_account_name TEXT,
    display_name TEXT,
    department TEXT,
    attributes JSONB NOT NULL DEFAULT '{}'::jsonb,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_directory_dn UNIQUE (domain_id, distinguished_name),
    CONSTRAINT ck_object_class CHECK (
        object_class IN (
            'domain', 'organizationalUnit', 'user',
            'group', 'computer', 'serviceConnectionPoint'
        )
    ),
    CONSTRAINT ck_dn_not_blank CHECK (
        length(trim(distinguished_name)) > 0
        AND distinguished_name ~* '^(CN|OU|DC)='
    ),
    CONSTRAINT ck_attributes_object CHECK (
        jsonb_typeof(attributes) = 'object'
    )
);

CREATE UNIQUE INDEX uq_domain_sam_account
    ON directory_objects(domain_id, lower(sam_account_name))
    WHERE sam_account_name IS NOT NULL;

CREATE INDEX idx_objects_class_enabled
    ON directory_objects(domain_id, object_class, enabled);

CREATE INDEX idx_objects_department
    ON directory_objects(domain_id, lower(department))
    WHERE object_class = 'user';

CREATE INDEX idx_objects_attributes_gin
    ON directory_objects USING GIN(attributes);

CREATE TABLE dns_records (
    dns_record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain_id BIGINT REFERENCES domains(domain_id),
    owner_name TEXT NOT NULL,
    record_type TEXT NOT NULL,
    record_value TEXT NOT NULL,
    priority INTEGER NOT NULL DEFAULT 0,
    weight INTEGER NOT NULL DEFAULT 0,
    port INTEGER,
    ttl_seconds INTEGER NOT NULL DEFAULT 3600,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_dns_owner CHECK (
        owner_name = lower(owner_name)
        AND owner_name !~ '\.\.'
        AND length(owner_name) <= 253
    ),
    CONSTRAINT ck_dns_type CHECK (
        record_type IN ('A', 'AAAA', 'CNAME', 'SRV', 'PTR')
    ),
    CONSTRAINT ck_dns_priority CHECK (priority >= 0),
    CONSTRAINT ck_dns_weight CHECK (weight >= 0),
    CONSTRAINT ck_dns_port CHECK (
        (record_type = 'SRV' AND port BETWEEN 1 AND 65535)
        OR (record_type <> 'SRV' AND port IS NULL)
    ),
    CONSTRAINT ck_dns_ttl CHECK (ttl_seconds BETWEEN 0 AND 2147483647),
    CONSTRAINT uq_dns_record UNIQUE (
        owner_name, record_type, record_value, port
    )
);

CREATE INDEX idx_dns_service_discovery
    ON dns_records(owner_name, record_type, priority, weight)
    WHERE enabled;

CREATE TABLE ldap_search_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain_id BIGINT NOT NULL REFERENCES domains(domain_id),
    base_dn TEXT NOT NULL,
    filter_description TEXT NOT NULL,
    requesting_identity TEXT NOT NULL,
    result_count INTEGER NOT NULL DEFAULT 0,
    succeeded BOOLEAN NOT NULL,
    failure_reason TEXT,
    executed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_search_result_count CHECK (result_count >= 0),
    CONSTRAINT ck_search_failure_reason CHECK (
        succeeded OR failure_reason IS NOT NULL
    )
);

CREATE INDEX idx_ldap_audit_domain_time
    ON ldap_search_audit(domain_id, executed_at DESC);

CREATE TABLE service_observations (
    observation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain_id BIGINT NOT NULL REFERENCES domains(domain_id),
    service_name TEXT NOT NULL,
    observation_status TEXT NOT NULL,
    details TEXT NOT NULL,
    observed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_observation_status CHECK (
        observation_status IN (
            'HEALTHY', 'DNS_FAILURE',
            'CONTROLLER_UNAVAILABLE', 'LDAP_FAILURE',
            'KERBEROS_FAILURE'
        )
    )
);

CREATE INDEX idx_service_observations_recent
    ON service_observations(domain_id, observed_at DESC);

-- PostgreSQL triggers enforce forest-root and child-domain consistency.
-- A production implementation would also validate complete ancestry,
-- DNS namespace ownership, and changes made to referenced parent domains.
CREATE OR REPLACE FUNCTION enforce_domain_hierarchy()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    parent_forest BIGINT;
    parent_name TEXT;
    forest_root TEXT;
BEGIN
    SELECT root_dns_name
      INTO forest_root
      FROM forests
     WHERE forest_id = NEW.forest_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Forest % does not exist', NEW.forest_id;
    END IF;

    IF NEW.is_forest_root THEN
        IF NEW.parent_domain_id IS NOT NULL THEN
            RAISE EXCEPTION 'Forest root cannot have a parent domain';
        END IF;

        IF NEW.dns_name <> forest_root THEN
            RAISE EXCEPTION
                'Root domain % must match forest root %',
                NEW.dns_name, forest_root;
        END IF;
    ELSE
        IF NEW.parent_domain_id IS NULL THEN
            RAISE EXCEPTION
                'A non-root domain must specify a parent domain';
        END IF;

        SELECT forest_id, dns_name
          INTO parent_forest, parent_name
          FROM domains
         WHERE domain_id = NEW.parent_domain_id;

        IF NOT FOUND THEN
            RAISE EXCEPTION
                'Parent domain % does not exist',
                NEW.parent_domain_id;
        END IF;

        IF parent_forest <> NEW.forest_id THEN
            RAISE EXCEPTION
                'Parent and child domains must belong to the same forest';
        END IF;

        IF NEW.dns_name NOT LIKE '%.' || parent_name
           OR length(NEW.dns_name) <= length(parent_name) + 1 THEN
            RAISE EXCEPTION
                'Domain % is not a child of %',
                NEW.dns_name, parent_name;
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_enforce_domain_hierarchy
BEFORE INSERT OR UPDATE OF forest_id, dns_name, parent_domain_id, is_forest_root
ON domains
FOR EACH ROW
EXECUTE FUNCTION enforce_domain_hierarchy();

-- Operational view: identify LDAP service endpoints discoverable through DNS.
CREATE VIEW v_domain_controller_discovery AS
SELECT
    d.dns_name AS domain_name,
    r.owner_name AS srv_query,
    r.record_value AS controller_target,
    r.port,
    r.priority,
    r.weight,
    r.ttl_seconds
FROM domains AS d
JOIN dns_records AS r ON r.domain_id = d.domain_id
WHERE r.enabled
  AND r.record_type = 'SRV'
  AND r.owner_name = '_ldap._tcp.' || d.dns_name;

CREATE VIEW v_enabled_forest_trusts AS
SELECT
    source.root_dns_name AS source_forest,
    target.root_dns_name AS target_forest,
    t.trust_scope,
    t.direction,
    t.is_transitive
FROM trusts AS t
JOIN forests AS source ON source.forest_id = t.source_forest_id
JOIN forests AS target ON target.forest_id = t.target_forest_id
WHERE t.is_enabled;

CREATE VIEW v_directory_objects AS
SELECT
    f.root_dns_name AS forest_root,
    d.dns_name AS domain_name,
    o.object_class,
    o.distinguished_name,
    o.sam_account_name,
    o.display_name,
    o.department,
    o.enabled,
    o.attributes
FROM directory_objects AS o
JOIN domains AS d ON d.domain_id = o.domain_id
JOIN forests AS f ON f.forest_id = d.forest_id;

