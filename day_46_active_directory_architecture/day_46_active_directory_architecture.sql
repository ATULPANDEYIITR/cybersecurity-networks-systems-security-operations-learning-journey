SELECT domain_name, srv_query, controller_target, port, priority, weight
FROM v_domain_controller_discovery
ORDER BY domain_name, priority, weight DESC;

-- Trust direction is stored explicitly. It must not be inferred from a
-- domain hierarchy or treated as equivalent to user authorization.
SELECT source_forest, target_forest, trust_scope, direction, is_transitive
FROM v_enabled_forest_trusts
ORDER BY source_forest, target_forest;

-- Service health is a separate concern from DNS record existence.
