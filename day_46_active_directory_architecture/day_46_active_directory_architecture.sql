-- Recursive trust reachability example. This query follows enabled,
-- transitive forest trusts and preserves direction. A direct edge can
-- reach its peer even when it is non-transitive, but cannot be traversed
-- to reach a third forest.
WITH RECURSIVE directed_trust_edges AS (
    SELECT
        source_forest_id AS from_forest,
        target_forest_id AS to_forest,
        is_transitive
    FROM trusts
    WHERE is_enabled
      AND trust_scope = 'FOREST'
      AND direction IN ('OUTBOUND', 'BIDIRECTIONAL')

    UNION ALL

    SELECT
        target_forest_id,
        source_forest_id,
        is_transitive
    FROM trusts
    WHERE is_enabled
      AND trust_scope = 'FOREST'
      AND direction IN ('INBOUND', 'BIDIRECTIONAL')
),
trust_walk(source_forest, current_forest, path, can_continue) AS (
    SELECT
        f.forest_id,
        f.forest_id,
        ARRAY[f.forest_id],
        TRUE
    FROM forests AS f
    WHERE f.root_dns_name = 'corp.example.com'

    UNION ALL

    SELECT
        walk.source_forest,
        edge.to_forest,
        walk.path || edge.to_forest,
        edge.is_transitive
    FROM trust_walk AS walk
    JOIN directed_trust_edges AS edge
      ON edge.from_forest = walk.current_forest
    WHERE walk.can_continue
      AND NOT edge.to_forest = ANY(walk.path)
)
SELECT
    source.root_dns_name AS source_forest,
    target.root_dns_name AS reachable_forest,
    walk.path
FROM trust_walk AS walk
JOIN forests AS source ON source.forest_id = walk.source_forest
JOIN forests AS target ON target.forest_id = walk.current_forest
WHERE walk.current_forest <> walk.source_forest
ORDER BY reachable_forest;
