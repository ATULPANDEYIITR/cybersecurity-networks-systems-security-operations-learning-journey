-- Linux Security Monitoring
-- PostgreSQL 14+ compatible relational model.
-- Demonstrates process, network, authentication, and persistence telemetry.
-- All sample records are synthetic. No host configuration is modified.

BEGIN;

CREATE SCHEMA IF NOT EXISTS linux_security;
SET search_path TO linux_security, public;

CREATE TABLE IF NOT EXISTS monitored_hosts (
    host_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostname TEXT NOT NULL UNIQUE,
    environment TEXT NOT NULL
        CHECK (environment IN ('development', 'test', 'staging', 'production')),
    last_seen TIMESTAMPTZ,
    CHECK (hostname <> '')
);

CREATE TABLE IF NOT EXISTS processes (
    process_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host_id BIGINT NOT NULL REFERENCES monitored_hosts(host_id) ON DELETE CASCADE,
    pid INTEGER NOT NULL CHECK (pid > 0),
    parent_pid INTEGER CHECK (parent_pid IS NULL OR parent_pid >= 0),
    effective_uid INTEGER NOT NULL CHECK (effective_uid >= 0),
    process_name TEXT NOT NULL,
    executable_path TEXT,
    command_line TEXT,
    effective_capabilities NUMERIC(20, 0) NOT NULL DEFAULT 0
        CHECK (effective_capabilities >= 0),
    observed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (host_id, pid, observed_at),
    CHECK (process_name <> '')
);

CREATE INDEX IF NOT EXISTS idx_processes_host_pid_time
    ON processes (host_id, pid, observed_at DESC);

CREATE INDEX IF NOT EXISTS idx_processes_executable
    ON processes (executable_path)
    WHERE executable_path IS NOT NULL;

CREATE TABLE IF NOT EXISTS network_connections (
    connection_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host_id BIGINT NOT NULL REFERENCES monitored_hosts(host_id) ON DELETE CASCADE,
    process_id BIGINT REFERENCES processes(process_id) ON DELETE SET NULL,
    protocol TEXT NOT NULL CHECK (protocol IN ('tcp', 'tcp6', 'udp', 'udp6')),
    connection_state TEXT NOT NULL,
    local_address INET,
    local_port INTEGER NOT NULL CHECK (local_port BETWEEN 0 AND 65535),
    remote_address INET,
    remote_port INTEGER CHECK (remote_port IS NULL OR remote_port BETWEEN 0 AND 65535),
    observed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_connections_host_state_time
    ON network_connections (host_id, connection_state, observed_at DESC);

CREATE INDEX IF NOT EXISTS idx_connections_local_port
    ON network_connections (local_port, connection_state);

CREATE TABLE IF NOT EXISTS authentication_events (
    auth_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host_id BIGINT NOT NULL REFERENCES monitored_hosts(host_id) ON DELETE CASCADE,
    event_time TIMESTAMPTZ NOT NULL,
    username TEXT NOT NULL,
    source_address INET,
    service_name TEXT NOT NULL DEFAULT 'sshd',
    outcome TEXT NOT NULL CHECK (outcome IN ('success', 'failure', 'invalid', 'locked')),
    authentication_method TEXT,
    session_id TEXT,
    CHECK (username <> '')
);

CREATE INDEX IF NOT EXISTS idx_auth_source_time
    ON authentication_events (host_id, source_address, event_time DESC);

CREATE INDEX IF NOT EXISTS idx_auth_user_time
    ON authentication_events (host_id, username, event_time DESC);

CREATE TABLE IF NOT EXISTS persistence_artifacts (
    artifact_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host_id BIGINT NOT NULL REFERENCES monitored_hosts(host_id) ON DELETE CASCADE,
    artifact_type TEXT NOT NULL CHECK (
        artifact_type IN ('systemd-unit', 'cron', 'authorized-key', 'autostart', 'init-script')
    ),
    artifact_path TEXT NOT NULL,
    owner_uid INTEGER NOT NULL CHECK (owner_uid >= 0),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    world_writable BOOLEAN NOT NULL DEFAULT FALSE,
    content_sha256 TEXT,
    command TEXT,
    observed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (host_id, artifact_path, observed_at)
);

CREATE INDEX IF NOT EXISTS idx_persistence_enabled
    ON persistence_artifacts (host_id, artifact_type, observed_at DESC)
    WHERE enabled;

CREATE TABLE IF NOT EXISTS security_findings (
    finding_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host_id BIGINT NOT NULL REFERENCES monitored_hosts(host_id) ON DELETE CASCADE,
    category TEXT NOT NULL CHECK (
        category IN ('process', 'network', 'authentication', 'persistence')
    ),
    severity TEXT NOT NULL CHECK (
        severity IN ('INFO', 'LOW', 'MEDIUM', 'HIGH', 'CRITICAL')
    ),
    title TEXT NOT NULL,
    evidence JSONB NOT NULL DEFAULT '{}'::JSONB,
    recommendation TEXT NOT NULL,
    first_seen TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    occurrence_count INTEGER NOT NULL DEFAULT 1 CHECK (occurrence_count > 0),
    status TEXT NOT NULL DEFAULT 'open'
        CHECK (status IN ('open', 'investigating', 'resolved', 'false_positive')),
    CHECK (last_seen >= first_seen)
);

CREATE INDEX IF NOT EXISTS idx_findings_open_severity
    ON security_findings (severity, last_seen DESC)
    WHERE status IN ('open', 'investigating');

CREATE INDEX IF NOT EXISTS idx_findings_evidence
    ON security_findings USING GIN (evidence);

