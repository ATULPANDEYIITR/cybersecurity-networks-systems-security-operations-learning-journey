-- A listener on a sensitive port deserves review; reachability depends on
-- routing, firewall rules, namespaces, and the actual bind address.
INSERT INTO security_findings (
    host_id, category, severity, title, evidence, recommendation
)
SELECT h.host_id,
       'network',
       CASE
           WHEN c.local_port = 2375 THEN 'HIGH'
           WHEN c.local_port IN (3306, 5432, 6379, 27017) THEN 'MEDIUM'
           WHEN c.local_address = '0.0.0.0'::INET
             OR c.local_address = '::'::INET THEN 'MEDIUM'
           ELSE 'LOW'
       END,
       CASE
           WHEN c.local_port = 2375 THEN 'Docker API listener requires exposure review'
           WHEN c.local_port IN (3306, 5432, 6379, 27017)
               THEN 'Database or cache listener requires network review'
           ELSE 'Listener requires exposure review'
       END,
       jsonb_build_object(
           'protocol', c.protocol,
           'address', c.local_address::TEXT,
           'port', c.local_port,
           'pid', p.pid,
           'process', p.process_name
       ),
       'Confirm listener ownership, firewall policy, authentication, and intended reachability.'
FROM monitored_hosts h
JOIN network_connections c ON c.host_id = h.host_id
LEFT JOIN processes p ON p.process_id = c.process_id
WHERE h.hostname = 'linux-web-01'
  AND c.connection_state = 'LISTEN'
  AND (
      c.local_port IN (2375, 3306, 5432, 6379, 27017)
      OR c.local_address = '0.0.0.0'::INET
      OR c.local_address = '::'::INET
  )
  AND NOT EXISTS (
      SELECT 1 FROM security_findings f
      WHERE f.host_id = h.host_id
        AND f.category = 'network'
        AND f.evidence->>'port' = c.local_port::TEXT
  );

-- Detect repeated authentication failures by source in a rolling time window.
WITH source_failures AS (
    SELECT host_id, source_address, COUNT(*) AS failure_count,
           MIN(event_time) AS first_failure,
           MAX(event_time) AS last_failure
    FROM authentication_events
    WHERE outcome IN ('failure', 'invalid')
      AND event_time >= CURRENT_TIMESTAMP - INTERVAL '1 day'
    GROUP BY host_id, source_address
    HAVING COUNT(*) >= 5
)
INSERT INTO security_findings (
    host_id, category, severity, title, evidence, recommendation,
    first_seen, last_seen, occurrence_count
)
SELECT sf.host_id,
       'authentication',
       CASE WHEN sf.failure_count >= 10 THEN 'HIGH' ELSE 'MEDIUM' END,
       'Repeated authentication failures from one source',
       jsonb_build_object(
           'source_address', sf.source_address::TEXT,
           'failure_count', sf.failure_count,
           'first_failure', sf.first_failure,
           'last_failure', sf.last_failure
       ),
       'Correlate with identity and network logs before applying an access restriction.',
       sf.first_failure, sf.last_failure, sf.failure_count::INTEGER
FROM source_failures sf
WHERE NOT EXISTS (
    SELECT 1 FROM security_findings f
    WHERE f.host_id = sf.host_id
      AND f.category = 'authentication'
      AND f.title = 'Repeated authentication failures from one source'
      AND f.evidence->>'source_address' = sf.source_address::TEXT
);

-- A successful event following multiple failures is a correlation signal.
WITH ordered_auth AS (
    SELECT a.*,
           COUNT(*) FILTER (WHERE outcome IN ('failure', 'invalid'))
           OVER (
               PARTITION BY host_id, source_address
               ORDER BY event_time
               RANGE BETWEEN INTERVAL '15 minutes' PRECEDING AND CURRENT ROW
           ) AS failures_in_window
    FROM authentication_events a
)
SELECT h.hostname,
       a.event_time,
       a.username,
       a.source_address,
       a.outcome,
       a.failures_in_window
FROM ordered_auth a
JOIN monitored_hosts h ON h.host_id = a.host_id
WHERE a.outcome = 'success'
  AND a.failures_in_window >= 5
ORDER BY a.event_time DESC;

-- Find enabled persistence artifacts with excessive write permissions or
-- paths that merit investigation. These indicators require contextual review.
SELECT h.hostname,
       a.artifact_type,
       a.artifact_path,
       a.owner_uid,
       a.world_writable,
       a.command,
       CASE
           WHEN a.world_writable THEN 'HIGH'
           WHEN a.artifact_path LIKE '/tmp/%'
             OR a.artifact_path LIKE '/dev/shm/%' THEN 'MEDIUM'
           ELSE 'LOW'
       END AS review_priority
FROM persistence_artifacts a
JOIN monitored_hosts h ON h.host_id = a.host_id
WHERE a.enabled
  AND (
      a.world_writable
      OR a.artifact_path LIKE '/tmp/%'
      OR a.artifact_path LIKE '/dev/shm/%'
  )
ORDER BY review_priority DESC, a.artifact_path;

-- Current unresolved findings are the operational triage view.
CREATE OR REPLACE VIEW unresolved_findings AS
SELECT f.finding_id,
       h.hostname,
       f.category,
       f.severity,
       f.title,
       f.evidence,
       f.recommendation,
       f.first_seen,
       f.last_seen,
       f.occurrence_count,
       f.status
FROM security_findings f
JOIN monitored_hosts h ON h.host_id = f.host_id
WHERE f.status IN ('open', 'investigating');

SELECT hostname, category, severity, title, evidence, recommendation
FROM unresolved_findings
ORDER BY
    CASE severity
        WHEN 'CRITICAL' THEN 5
        WHEN 'HIGH' THEN 4
        WHEN 'MEDIUM' THEN 3
        WHEN 'LOW' THEN 2
        ELSE 1
    END DESC,
    last_seen DESC;

-- Transactional integrity: all schema and demonstration data are committed together.
COMMIT;
